RU_FIRST_NAMES = frozenset(_NAMES.split())


def ru_first_name(contact: dict) -> str:
    for src in (contact.get("NAME"), contact.get("LAST_NAME") if not (contact.get("NAME") or "").strip() else None):
        words = re.findall(r"[А-Яа-яЁё-]+", src or "")
        if words:
            w = words[0].capitalize()
            return w if w in RU_FIRST_NAMES else ""
    return ""
